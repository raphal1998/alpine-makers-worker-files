KNOWN_M = {"M0", "M1", "M2", "M3", "M4", "M5", "M6", "M7", "M8", "M9", "M30"}
PRINTER_M = {"M82", "M83", "M104", "M105", "M106", "M107", "M109", "M140", "M141", "M190", "M191", "M204", "M220",
             "M221", "M600"}
PRINTER_G = {"G29"}
PRINTER_MARKERS = re.compile(r";\s*(FLAVOR|LAYER|LAYER_COUNT|TYPE:|GENERATED BY|GENERATED WITH)", re.IGNORECASE)
EXTRA_AXES = set("ABCUVW")
CANNED = {"G73", "G81", "G82", "G83"}
_TOKEN = re.compile(r"([A-Z])\s*([-+]?(?:[0-9]+\.?[0-9]*|\.[0-9]+))?")


def _word(letter, value):
    """« G01 » → « G1 » ; « G54.1 » conservé."""
    if value is None:
        return letter
    number = float(value)
    if number.is_integer():
        return f"{letter}{int(number)}"
    return f"{letter}{number:g}"


def _strip(line):
    """Retire commentaires, numéro de ligne et caractères de bloc ; rend (texte, commentaire point-virgule)."""
    semicolon = ""
    if ";" in line:
        line, semicolon = line.split(";", 1)
        semicolon = ";" + semicolon
    line = re.sub(r"\([^)]*\)?", " ", line)
    text = line.strip().upper()
    if text.startswith("/"):
        text = text[1:]
    if text.startswith("%"):
        text = ""
    return text, semicolon


class _Program:
    """Interprète tolérant : état modal, positions en mm, mouvements élémentaires."""

    def __init__(self):
        self.units = None          # "mm" | "inch"
        self.distance = None       # "abs" | "inc"
        self.plane = "G17"
        self.motion = None
        self.canned_return = "G98"
        self.feed = None           # mm/min
        self.spindle = 0.0
        self.spindle_on = False
        self.coolant_on = False
        self.tool = None
        self.position = [None, None, None]
        self.moves = []            # dicts : kind, line, a, b, feed, tool, arc
        self.events = []           # (line, kind, data)
        self.ended = False
        self.end_line = None

    def scale(self):
        return INCH_MM if self.units == "inch" else 1.0


def _parse(text):
    program = _Program()
    for number, raw in enumerate(str(text).splitlines(), start=1):
        if program.ended:
            # Après M2/M30 le contrôleur s'arrête ; le reste n'est pas exécuté.
            if raw.strip():
                program.events.append((number, "after_end", raw.strip()[:40]))
            continue
        clean, semicolon = _strip(raw)
        if semicolon and PRINTER_MARKERS.search(semicolon):
            program.events.append((number, "printer", semicolon.strip()[:40]))
        if not clean:
            continue
        tokens = [(match.group(1), match.group(2)) for match in _TOKEN.finditer(clean)]
        _execute(program, number, tokens)
    return program


def _execute(program, line, tokens):
    words, values, bare = [], {}, set()
    for letter, value in tokens:
        if letter in ("G", "M"):
            if value is None:
                program.events.append((line, "unsupported", letter))
                continue
            words.append(_word(letter, value))
        elif letter == "N":
            continue
        elif value is None:
            bare.add(letter)
        else:
            values[letter] = float(value)
    for word in words:
        if word in PRINTER_M or word in PRINTER_G:
            program.events.append((line, "printer", word))
        elif word.startswith("G") and word not in KNOWN_G:
            program.events.append((line, "unsupported", word))
        elif word.startswith("M") and word not in KNOWN_M:
            program.events.append((line, "unsupported", word))
        program.events.append((line, "word", word))
    if "E" in values:
        program.events.append((line, "printer", "E"))
    if "G28" in words and bare & {"X", "Y", "Z"}:
        program.events.append((line, "printer", "G28 sans valeur"))
    for letter in EXTRA_AXES:
        if letter in values:
            program.events.append((line, "axis", letter))
    scale_before = program.scale()
    # Ordre RS274 : F, S, T, M6, broche, arrosage, plan, unités, distance, mouvement, fin.
    for word in words:
        if word in ("G20", "G21"):
            program.units = "inch" if word == "G20" else "mm"
            program.events.append((line, "units", program.units))
        elif word in ("G90", "G91"):
            program.distance = "abs" if word == "G90" else "inc"
            program.events.append((line, "distance", program.distance))
        elif word in ("G17", "G18", "G19"):
            program.plane = word
        elif word in ("G98", "G99"):
            program.canned_return = word
    scale = program.scale() if program.units else scale_before
    if "F" in values:
        program.feed = values["F"] * scale
        program.events.append((line, "feed", program.feed))
    if "S" in values:
        program.spindle = values["S"]
        program.events.append((line, "spindle_speed", program.spindle))
    if "T" in values:
        program.tool = int(values["T"])
        program.events.append((line, "tool", program.tool))
    if "M6" in words:
        program.events.append((line, "tool_change", program.tool))
    for word in words:
        if word in ("M3", "M4"):
            program.spindle_on = True
            program.events.append((line, "spindle_on", program.spindle))
        elif word == "M5":
            program.spindle_on = False
            program.events.append((line, "spindle_off", None))
        elif word in ("M7", "M8"):
            program.coolant_on = True
        elif word == "M9":
            program.coolant_on = False
    motion_words = [word for word in words if word in ("G0", "G1", "G2", "G3", "G80") or word in CANNED]
    non_modal = [word for word in words if word in ("G28", "G53", "G4", "G10")]
    if motion_words:
        program.motion = None if motion_words[-1] == "G80" else motion_words[-1]
    has_axis = any(letter in values for letter in "XYZ")
    if "G28" in non_modal or "G53" in non_modal:
        # Mouvement en coordonnées machine : la position pièce devient inconnue.
        for index, letter in enumerate("XYZ"):
            if letter in values or "G28" in non_modal:
                program.position[index] = None
        program.events.append((line, "machine_move", None))
    elif "G4" in non_modal:
        program.events.append((line, "dwell", values.get("P", 0.0)))
    elif "G10" in non_modal:
        pass
    elif program.motion and (has_axis or (program.motion in ("G2", "G3") and any(k in values for k in "IJKR"))):
        _move(program, line, values, scale)
    for word in words:
        if word in ("M0", "M1"):
            program.events.append((line, "pause", word))
        elif word in ("M2", "M30"):
            program.ended = True
            program.end_line = line
            program.events.append((line, "end", word))


def _target(program, values, scale):
    target = list(program.position)
    for index, letter in enumerate("XYZ"):
        if letter in values:
            value = values[letter] * scale
            if program.distance == "inc":
                target[index] = None if program.position[index] is None else program.position[index] + value
            else:
                target[index] = value
    return target


def _move(program, line, values, scale):
    start = list(program.position)
    motion = program.motion
    program.events.append((line, "motion", motion))
    if motion in CANNED:
        _canned(program, line, values, scale)
        return
    end = _target(program, values, scale)
    arc = None
    if motion in ("G2", "G3"):
        arc = _arc(program, start, end, values, scale, clockwise=motion == "G2")
    kind = "rapid" if motion == "G0" else "cut"
    program.moves.append({"kind": kind, "line": line, "a": start, "b": end, "feed": program.feed,
                          "tool": program.tool, "arc": arc, "spindle_on": program.spindle_on})
    program.position = end


def _canned(program, line, values, scale):
    """Perçage G73/G81/G82/G83 : rapide XY, rapide au plan R, plongée à Z, retour."""
    initial_z = program.position[2]
    xy_target = _target(program, {key: values[key] for key in ("X", "Y") if key in values}, scale)
    if "Z" in values:
        program.canned_z = values["Z"] * scale
    if "R" in values:
        program.canned_r = values["R"] * scale
    bottom = getattr(program, "canned_z", None)
    r_plane = getattr(program, "canned_r", initial_z)
    base = dict(line=line, feed=program.feed, tool=program.tool, arc=None, spindle_on=program.spindle_on)
    start = list(program.position)
    above = [xy_target[0], xy_target[1], start[2]]
    program.moves.append({"kind": "rapid", "a": start, "b": above, **base})
    current = above
    if r_plane is not None and (current[2] is None or r_plane < current[2]):
        lowered = [current[0], current[1], r_plane]
        program.moves.append({"kind": "rapid", "a": current, "b": lowered, **base})
        current = lowered
    if bottom is not None:
        down = [current[0], current[1], bottom]
        program.moves.append({"kind": "cut", "a": current, "b": down, **base})
        retract = initial_z if program.canned_return == "G98" and initial_z is not None else r_plane
        up = [current[0], current[1], retract]
        program.moves.append({"kind": "rapid", "a": down, "b": up, **base})
        current = up
    program.position = current


def _arc(program, start, end, values, scale, clockwise):
    """Centre, rayon et angles d'un arc dans le plan courant (approximation si données incomplètes)."""
    if None in start or None in end:
        return None
    axes = {"G17": (0, 1, "I", "J"), "G18": (2, 0, "K", "I"), "G19": (1, 2, "J", "K")}[program.plane]
    u, v, cu, cv = axes
    su, sv, eu, ev = start[u], start[v], end[u], end[v]
    if "R" in values:
        radius = values["R"] * scale
        chord = math.hypot(eu - su, ev - sv)
        if chord < 1e-9 or abs(radius) < chord / 2.0 - 1e-6:
            return None
        middle_u, middle_v = (su + eu) / 2.0, (sv + ev) / 2.0
        height = math.sqrt(max(radius * radius - (chord / 2.0) ** 2, 0.0))
        direction = (1 if clockwise else -1) * (1 if radius > 0 else -1)
        center_u = middle_u + direction * height * (ev - sv) / chord
        center_v = middle_v - direction * height * (eu - su) / chord
        radius = abs(radius)
    else:
        center_u = su + values.get(cu, 0.0) * scale
        center_v = sv + values.get(cv, 0.0) * scale
        radius = math.hypot(su - center_u, sv - center_v)
    start_angle = math.atan2(sv - center_v, su - center_u)
    end_angle = math.atan2(ev - center_v, eu - center_u)
    if clockwise:
        sweep = start_angle - end_angle
    else:
        sweep = end_angle - start_angle
    sweep %= 2 * math.pi
    if sweep < 1e-9:
        sweep = 2 * math.pi  # cercle complet
    return {"u": u, "v": v, "center": (center_u, center_v), "radius": radius, "start": start_angle,
            "sweep": sweep, "clockwise": clockwise}


def _length(move):
    a, b = move["a"], move["b"]
    if None in a or None in b:
        return 0.0
    arc = move["arc"]
    if arc:
        planar = arc["radius"] * arc["sweep"]
        other = [index for index in range(3) if index not in (arc["u"], arc["v"])][0]
        return math.hypot(planar, b[other] - a[other])
    return math.dist(a, b)


def _arc_points(move, count):
    arc, a, b = move["arc"], move["a"], move["b"]
    other = [index for index in range(3) if index not in (arc["u"], arc["v"])][0]
    points = []
    for step in range(1, count + 1):
        fraction = step / count
        angle = arc["start"] + (-1 if arc["clockwise"] else 1) * arc["sweep"] * fraction
        point = [0.0, 0.0, 0.0]
        point[arc["u"]] = arc["center"][0] + arc["radius"] * math.cos(angle)
        point[arc["v"]] = arc["center"][1] + arc["radius"] * math.sin(angle)
        point[other] = a[other] + (b[other] - a[other]) * fraction
        points.append(point)
    return points


def _extremes(move):
    """Points qui bornent un mouvement : extrémités, et pour un arc les extrêmes atteints sur chaque axe."""
    points = [point for point in (move["a"], move["b"]) if None not in point]
    arc = move["arc"]
    if arc and None not in move["a"]:
        for quarter in range(4):
            angle = quarter * math.pi / 2.0
            offset = (angle - arc["start"]) if not arc["clockwise"] else (arc["start"] - angle)
            if offset % (2 * math.pi) <= arc["sweep"] + 1e-9:
                point = list(move["a"])
                point[arc["u"]] = arc["center"][0] + arc["radius"] * math.cos(angle)
                point[arc["v"]] = arc["center"][1] + arc["radius"] * math.sin(angle)
                points.append(point)
    return points


class _Report:
    def __init__(self):
        self.errors, self.warnings = {}, {}

    def add(self, code, line, detail=""):
        target = self.errors if code in ERROR_CODES else self.warnings
        if code in target:
            target[code]["count"] += 1
            return
        message = MESSAGES[code] + (f" ({detail})" if detail else "")
        entry = {"code": code, "line": int(line or 0), "message": message, "count": 1}
        if target is self.warnings:
            entry["ackable"] = True
        target[code] = entry


def _tool_limits(project):
    """Avances maximales prévues par outil (outil et surcharges des opérations), en mm/min."""
    if not isinstance(project, dict):
        return {}, {}
    factor = INCH_MM if project.get("units") == "inch" else 1.0
    feeds, rpms = {}, {}
    for tool in project.get("tools") or []:
        values = [tool.get(key) for key in ("feed_xy", "feed_plunge", "feed_ramp") if tool.get(key)]
        feeds[tool["number"]] = max(values) * factor if values else None
        rpms[tool["number"]] = tool.get("max_rpm")
    for operation in project.get("operations") or []:
        number = operation.get("tool")
        for key in ("feed_xy", "feed_plunge"):
            if operation.get(key) and number in feeds and feeds[number] is not None:
                feeds[number] = max(feeds[number], operation[key] * factor)
    return feeds, rpms


def check_gcode(text, project=None, machine=None, *, stock=None):
    """Relit ``text`` ; ``stock`` = {"min": [x, y, z], "max": [x, y, z]} en mm dans le repère pièce (facultatif)."""
    if machine is None and isinstance(project, dict):
        machine = project.get("machine")
    program = _parse(text)
    report = _Report()
    feeds_by_tool, rpm_by_tool = _tool_limits(project)
    known_tools = set(feeds_by_tool) if isinstance(project, dict) and project.get("tools") else None
    factor = INCH_MM if isinstance(project, dict) and project.get("units") == "inch" else 1.0
    retract = None
    if isinstance(project, dict) and isinstance(project.get("heights"), dict):
        retract = float(project["heights"].get("retract") or 0.0) * factor
    stock_top = float(stock["max"][2]) if stock else 0.0
    stock_bottom = float(stock["min"][2]) if stock else None
    unsupported = set((machine or {}).get("unsupported_commands") or [])
    max_feed = (machine or {}).get("max_feed")
    spindle = (machine or {}).get("spindle") or {}
    units_seen = distance_seen = False
    spindle_started = False
    for line, kind, data in program.events:
        if kind == "printer":
            report.add("printer_gcode", line, str(data))
        elif kind == "axis":
            report.add("axis_not_available", line, f"axe {data}")
        elif kind == "unsupported":
            report.add("unsupported_command", line, str(data))
        elif kind == "word" and data in unsupported:
            report.add("unsupported_command", line, f"{data} non pris en charge par cette machine")
        elif kind == "units":
            units_seen = True
        elif kind == "distance":
            distance_seen = True
        elif kind == "motion":
            if not (units_seen and distance_seen):
                report.add("move_before_init", line)
        elif kind == "tool" and known_tools is not None and data not in known_tools and data != 0:
            report.add("tool_unknown", line, f"T{data}")
        elif kind == "spindle_on":
            spindle_started = True
        elif kind == "spindle_speed" and data:
            if spindle.get("max_rpm") and data > spindle["max_rpm"] + 1e-6:
                report.add("spindle_above_limit", line, f"S{data:g} > {spindle['max_rpm']:g} tr/min (machine)")
            elif spindle.get("min_rpm") and data + 1e-6 < spindle["min_rpm"]:
                report.add("spindle_below_min", line, f"S{data:g} < {spindle['min_rpm']:g} tr/min")
        elif kind == "feed" and max_feed and data > max_feed * 1.0001:
            report.add("feed_above_machine", line, f"F{data:g} > {max_feed:g} mm/min")
    if not any(kind == "units" for _line, kind, _data in program.events):
        report.add("unit_mode_missing", 0)
    if not any(kind == "distance" for _line, kind, _data in program.events):
        report.add("distance_mode_missing", 0)
    if not program.ended:
        report.add("program_end_missing", 0)
    if not spindle_started and any(move["kind"] == "cut" for move in program.moves):
        report.add("spindle_never_started", next(move["line"] for move in program.moves if move["kind"] == "cut"))
    # Vitesse de broche au-dessus du maximum de l'outil courant.
    current_tool = None
    for line, kind, data in program.events:
        if kind == "tool":
            current_tool = data
        elif kind == "spindle_speed" and data and rpm_by_tool.get(current_tool) and data > rpm_by_tool[current_tool] + 1e-6:
            report.add("spindle_above_limit", line, f"S{data:g} > {rpm_by_tool[current_tool]:g} tr/min (outil T{current_tool})")

    lows, highs = [math.inf] * 3, [-math.inf] * 3
    rapid_length = cut_length = 0.0
    time_min = 0.0
    rapid_speed = float((machine or {}).get("max_rapid") or max_feed or 1000.0)
    tools_used = []
    for move in program.moves:
        if move["tool"] is not None and move["tool"] not in tools_used and move["kind"] == "cut":
            tools_used.append(move["tool"])
        for point in _extremes(move):
            for axis in range(3):
                lows[axis] = min(lows[axis], point[axis])
                highs[axis] = max(highs[axis], point[axis])
        length = _length(move)
        if move["kind"] == "rapid":
            rapid_length += length
            time_min += length / rapid_speed
            a, b = move["a"], move["b"]
            horizontal = None not in a and None not in b and math.hypot(b[0] - a[0], b[1] - a[1]) > 1e-6
            if horizontal and retract is not None and min(a[2], b[2]) < stock_top + retract - 0.01:
                report.add("rapid_below_safe", move["line"], f"Z{min(a[2], b[2]):.3f} mm")
        else:
            cut_length += length
            if move["feed"] is None:
                report.add("feed_missing_on_g1", move["line"])
            else:
                time_min += length / max(move["feed"], 1e-6)
                limit = feeds_by_tool.get(move["tool"])
                if limit and move["feed"] > limit * 1.01:
                    report.add("feed_above_tool", move["line"], f"F{move['feed']:g} > {limit:g} mm/min (T{move['tool']})")
            if not move["spindle_on"] and spindle_started:
                report.add("spindle_never_started", move["line"], "broche arrêtée pendant une coupe")
            if stock_bottom is not None and None not in move["b"]:
                lowest = move["b"][2]
                if lowest < stock_bottom - 0.01:
                    report.add("z_below_stock_bottom", move["line"], f"Z{lowest:.3f} mm")
    for line, kind, data in program.events:
        if kind == "dwell":
            time_min += float(data or 0.0) / 60.0
    if program.coolant_on:
        report.add("coolant_not_stopped", program.end_line or 0)
    if program.spindle_on:
        report.add("spindle_not_stopped_at_end", program.end_line or 0)
    has_bounds = all(math.isfinite(value) for value in lows + highs)
    travel = (machine or {}).get("travel") or {}
    if has_bounds:
        for index, axis in enumerate("xyz"):
            extent = highs[index] - lows[index]
            if travel.get(axis) and extent > float(travel[axis]) + 0.01:
                report.add("outside_travel", 0, f"{axis.upper()} : {extent:.1f} mm parcourus pour {float(travel[axis]):g} mm de course")
    time_s = time_min * 60.0
    if time_s > LONG_PROGRAM_S:
        report.add("time_estimate_long", 0, f"{time_s / 3600.0:.1f} h")
    stats = {
        "units": "mm",
        "program_units": program.units,
        "lines": len(str(text).splitlines()),
        "moves": len(program.moves),
        "bounds": {"min": [round(value, 4) for value in lows], "max": [round(value, 4) for value in highs]}
        if has_bounds else None,
        "length_mm": {"rapid": round(rapid_length, 3), "cut": round(cut_length, 3), "total": round(rapid_length + cut_length, 3)},
        "time_estimate_s": round(time_s, 1),
        "tools_used": tools_used,
        "tool_changes": sum(1 for _line, kind, _data in program.events if kind == "tool_change"),
        "pauses": sum(1 for _line, kind, _data in program.events if kind == "pause"),
    }
    errors = sorted(report.errors.values(), key=lambda entry: ERROR_CODES.index(entry["code"]))
    warnings = sorted(report.warnings.values(), key=lambda entry: WARNING_CODES.index(entry["code"]))
    return {"ok": not errors, "errors": errors, "warnings": warnings, "stats": stats}


def simulation_segments(text, limit=20000):
    """Segments pour l'aperçu : {"k": rapid|cut|plunge|tool, "t", "a", "b", "f"} en mm, sous-échantillonnés au-delà de ``limit``."""
    limit = max(1, int(limit))
    program = _parse(text)
    segments = []
    tool_lines = {line: data for line, kind, data in program.events if kind == "tool_change"}
    emitted_tools = set()
    for move in program.moves:
        point = move["a"] if None not in move["a"] else move["b"]
        for line in [line for line in tool_lines if line <= move["line"] and line not in emitted_tools]:
            if None in point:
                break  # position encore inconnue : le changement sera placé au premier point connu
            emitted_tools.add(line)
            position = [round(value, 4) for value in point]
            segments.append({"k": "tool", "t": tool_lines[line], "a": position, "b": position, "f": None})
        a, b = move["a"], move["b"]
        if None in a or None in b:
            continue
        points = _arc_points(move, max(2, min(32, int(move["arc"]["sweep"] / (math.pi / 16)) + 1))) if move["arc"] else [b]
        previous = a
        for point in points:
            if move["kind"] == "rapid":
                kind = "rapid"
            elif abs(point[0] - previous[0]) < 1e-9 and abs(point[1] - previous[1]) < 1e-9 and point[2] < previous[2]:
                kind = "plunge"
            else:
                kind = "cut"
            segments.append({"k": kind, "t": move["tool"], "a": [round(value, 4) for value in previous],
                             "b": [round(value, 4) for value in point],
                             "f": None if kind == "rapid" or move["feed"] is None else round(move["feed"], 3)})
            previous = point
    truncated = len(segments) > limit
    if truncated:
        total = len(segments)
        segments = [segments[int(index * total / limit)] for index in range(limit)]
    return {"units": "mm", "segments": segments, "truncated": truncated, "limit": limit}
