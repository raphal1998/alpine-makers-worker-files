"""Relecture indépendante d'un programme de fraisage (G-code) avant de le rendre.

Indépendant du générateur : ce module ne connaît pas FreeCAD et relit le texte
produit par le post-processeur comme le ferait un contrôleur prudent. Il ne
modifie jamais le programme. Bibliothèque standard seulement (livré au Worker et
importé par le site).

``check_gcode(text, project, machine)`` rend ``{"ok", "errors", "warnings", "stats"}``.
Les erreurs sont structurelles et jamais acquittables ; les avertissements portent
``ackable: True``. Une entrée par code (première ligne concernée) avec ``count``.

Limites assumées :
- les courses sont contrôlées par l'ÉTENDUE du programme sur chaque axe (le
  décalage entre origine pièce et origine machine n'est pas connu ici) ;
- les mouvements G28 / G53 rendent la position inconnue (elle n'entre pas dans
  les bornes) ;
- l'estimation de temps ne tient compte ni des accélérations ni des
  changements d'outil manuels : elle est indicative.
"""
